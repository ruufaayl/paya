"""Run representative journeys on a fresh database and write the real ledger postings to evidence.

Run:  PAYA_DATABASE_URL=postgresql+psycopg://paya@localhost:5433/paya_evidence \
      python docs/architecture/tools/ledger_examples.py
Writes evidence/ledger/worked-examples.md. Everything below is produced by the system, not typed by hand.
"""
import os
from pathlib import Path

from sqlalchemy import select

from paya import db, events, integrity, ledger, notifications, payments, recon
from paya.db import session_scope
from paya.models import Account, Journal, LedgerEntry, Transaction, User
from paya.rail import chaos, rail
from paya.seed import seed

assert "evidence" in os.environ.get("PAYA_DATABASE_URL", ""), "point PAYA_DATABASE_URL at a throwaway evidence database"
db.drop_schema()
db.create_schema()
seed()
notifications.register()
OUT = Path(__file__).resolve().parents[3] / "evidence" / "ledger"
OUT.mkdir(parents=True, exist_ok=True)

with session_scope() as s:
    sara = s.execute(select(User.customer_id).where(User.username == "sara")).scalar_one()
    zarak = s.execute(select(User.customer_id).where(User.username == "zarak")).scalar_one()
    chai = s.execute(select(User.merchant_id).where(User.username == "ayesha.cashier")).scalar_one()


def run_payment(amount_minor: int, customer, mode: str | None = None, label: str = "") -> str:
    if mode:
        chaos.queue(mode)
    pr = payments.create_payment_request(chai, amount_minor, f"EV-{label}", "ayesha.cashier")
    txn = payments.initiate_payment(customer_id=customer, payment_request_id=pr.id, actor="demo",
                                    correlation_id=f"corr-ev-{label}")
    if txn.status == "PENDING":
        payments.dispatch(txn.id)
    events.relay_once()
    return txn.txn_ref


def postings(ref: str) -> list[str]:
    rows = []
    with session_scope() as s:
        t = s.execute(select(Transaction).where(Transaction.txn_ref == ref)).scalar_one()
        ids = [t.id] + list(s.execute(select(Transaction.id).where(Transaction.original_txn_id == t.id)).scalars())
        accts = {a.id: a for a in s.execute(select(Account)).scalars()}
        for j in s.execute(select(Journal).where(Journal.txn_id.in_(ids)).order_by(Journal.created_at)).scalars():
            for e in s.execute(select(LedgerEntry).where(LedgerEntry.journal_id == j.id).order_by(LedgerEntry.id)).scalars():
                a = accts[e.account_id]
                dr = f"{e.amount_minor / 100:,.2f}" if e.direction == "D" else ""
                cr = f"{e.amount_minor / 100:,.2f}" if e.direction == "C" else ""
                rows.append(f"| {j.posting_type} | {j.reason_code} | {a.code} {a.name}{' (' + a.owner_type.lower() + ')' if a.owner_type else ''} | {dr} | {cr} | {j.initiated_via}{', approved ' + j.approved_by if j.approved_by else ''} |")
        status = t.status
    return [f"Final status: **{status}**", "", "| Journal | Reason | Account | Debit (PKR) | Credit (PKR) | How |",
            "|---|---|---|---:|---:|---|", *rows] if rows else [f"Final status: **{status}**", "", "_No journal: no money moved._"]


md = ["# Worked ledger examples (generated by the system)", "",
      "Produced by `docs/architecture/tools/ledger_examples.py` on a fresh database with synthetic seed data.",
      "Every row below was written by Paya's posting service. Amounts in PKR (stored as integer paisa).", ""]
cases = [
    ("E1 Normal payment, PKR 2,450", lambda: run_payment(245_000, sara, None, "E1")),
    ("E2 Rail rejects after debit: compensating reversal, PKR 999", lambda: run_payment(99_900, sara, "REJECT", "E2")),
    ("E3 Timeout with unknown outcome, resolved by status enquiry, PKR 800", lambda: (lambda r: (payments.run_status_enquiries(force=True), events.relay_once(), r)[-1])(run_payment(80_000, sara, "TIMEOUT_AFTER_ACCEPT", "E3"))),
    ("E4 Compliance hold (watch-list): no money moves until a human decides, PKR 600", lambda: run_payment(60_000, zarak, None, "E4")),
    ("E5 Ops reversal approved by Finance (maker-checker), PKR 400", None),
]
refs = {}
for title, fn in cases:
    if fn is None:
        chaos.set_mode("TIMEOUT_NO_RECORD")
        ref = run_payment(40_000, sara, None, "E5")
        chaos.set_mode("DOWN")
        a = payments.request_reversal(txn_ref=ref, actor="sana.ops", actor_role="OPS", reason="Rail silent beyond SLA")
        payments.approve_reversal(approval_id=a.id, actor="rabia.finance", actor_role="FINANCE")
        chaos.reset()
    else:
        ref = fn()
    refs[title] = ref
    md += [f"## {title}", "", f"Reference `{ref}`.", "", *postings(ref), ""]

summary = recon.run(rail.settlement_file(__import__("datetime").datetime.now(__import__("datetime").timezone.utc).date()), actor="rabia.finance")
md += ["## Reconciliation run on the same day", "", "```json", __import__("json").dumps(summary, indent=2), "```", ""]
with session_scope() as s:
    tb = ledger.trial_balance(s)
    md += ["## Trial balance after all examples", "", "| Account | Type | Debits | Credits | Balance |", "|---|---|---:|---:|---:|"]
    md += [f"| {a['code']} {a['name']} | {a['type']} | {a['debit_minor'] / 100:,.2f} | {a['credit_minor'] / 100:,.2f} | {a['balance_minor'] / 100:,.2f} |" for a in tb["accounts"]]
    md += ["", f"**Total debits {tb['total_debit_minor'] / 100:,.2f} = total credits {tb['total_credit_minor'] / 100:,.2f} → balanced: {tb['balanced']}**", ""]
    ic = integrity.run(s)
    md += ["## Integrity checks after all examples", "", f"Overall: **{ic['overall']}**", "", "| Layer | Check | Status | Value |", "|---|---|---|---|"]
    md += [f"| {c['layer']} | {c['check']} | {c['status']} | `{c['value']}` |" for c in ic["checks"]]
(OUT / "worked-examples.md").write_text("\n".join(md) + "\n")
print("wrote", OUT / "worked-examples.md")
